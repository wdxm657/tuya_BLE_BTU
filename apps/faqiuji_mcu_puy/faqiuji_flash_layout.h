#ifndef FAQIUJI_FLASH_LAYOUT_H
#define FAQIUJI_FLASH_LAYOUT_H

/*
 * PY32F040 128 KB Flash layout. All END addresses are exclusive.
 */
#define FAQIUJI_FLASH_BASE                 0x08000000UL
#define FAQIUJI_FLASH_SIZE                 0x00020000UL
#define FAQIUJI_FLASH_END                  (FAQIUJI_FLASH_BASE + FAQIUJI_FLASH_SIZE)
#define FAQIUJI_FLASH_PAGE_SIZE            0x00000100UL
#define FAQIUJI_FLASH_SECTOR_SIZE          0x00002000UL

#define FAQIUJI_FLASH_BOOT_BASE            FAQIUJI_FLASH_BASE
#define FAQIUJI_FLASH_BOOT_SIZE            0x00004000UL
#define FAQIUJI_FLASH_BOOT_END             (FAQIUJI_FLASH_BOOT_BASE + FAQIUJI_FLASH_BOOT_SIZE)

#define FAQIUJI_FLASH_APP_A_BASE           FAQIUJI_FLASH_BOOT_END
#define FAQIUJI_FLASH_APP_A_SIZE           0x0000C000UL
#define FAQIUJI_FLASH_APP_A_END            (FAQIUJI_FLASH_APP_A_BASE + FAQIUJI_FLASH_APP_A_SIZE)

#define FAQIUJI_FLASH_APP_B_BASE           FAQIUJI_FLASH_APP_A_END
#define FAQIUJI_FLASH_APP_B_SIZE           0x0000C000UL
#define FAQIUJI_FLASH_APP_B_END            (FAQIUJI_FLASH_APP_B_BASE + FAQIUJI_FLASH_APP_B_SIZE)

#define FAQIUJI_FLASH_OTA_META_BASE        FAQIUJI_FLASH_APP_B_END
#define FAQIUJI_FLASH_OTA_META_SIZE        0x00002000UL
#define FAQIUJI_FLASH_OTA_META_END         (FAQIUJI_FLASH_OTA_META_BASE + FAQIUJI_FLASH_OTA_META_SIZE)

#define FAQIUJI_FLASH_CONFIG_BASE          FAQIUJI_FLASH_OTA_META_END
#define FAQIUJI_FLASH_CONFIG_SIZE          0x00002000UL
#define FAQIUJI_FLASH_CONFIG_END           (FAQIUJI_FLASH_CONFIG_BASE + FAQIUJI_FLASH_CONFIG_SIZE)

/*
 * Both slot metadata records share the 8 KB META region. Each slot uses a
 * separate 4 KB half-region: marker page, record page, and factory guard.
 */
#define FAQIUJI_META_A_BASE                FAQIUJI_FLASH_OTA_META_BASE
#define FAQIUJI_META_B_BASE                (FAQIUJI_META_A_BASE + 0x00001000UL)
#define FAQIUJI_META_RECORD_OFFSET         FAQIUJI_FLASH_PAGE_SIZE
#define FAQIUJI_META_FACTORY_GUARD_OFFSET  (2U * FAQIUJI_FLASH_PAGE_SIZE)

#if defined(FAQIUJI_APP_SLOT_B)
#error "Unified OTA firmware must run from APP A; APP B is download storage"
#endif
#define FAQIUJI_APP_BASE                   FAQIUJI_FLASH_APP_A_BASE
#define FAQIUJI_APP_VERSION_MAJOR          1
#define FAQIUJI_APP_VERSION_MINOR          0
#define FAQIUJI_APP_VERSION_PATCH          2

#if (FAQIUJI_APP_VERSION_MAJOR < 0) || (FAQIUJI_APP_VERSION_MAJOR > 255) || \
    (FAQIUJI_APP_VERSION_MINOR < 0) || (FAQIUJI_APP_VERSION_MINOR > 255) || \
    (FAQIUJI_APP_VERSION_PATCH < 0) || (FAQIUJI_APP_VERSION_PATCH > 255)
#error "Firmware version components must be in the range 0..255"
#endif
/* Tuya uses three bytes: major.minor.patch, e.g. 1.0.0 = 0x010000. */
#define FAQIUJI_APP_VERSION                ((FAQIUJI_APP_VERSION_MAJOR * 0x10000UL) | \
                                           (FAQIUJI_APP_VERSION_MINOR * 0x100UL) | \
                                            FAQIUJI_APP_VERSION_PATCH)

#if (FAQIUJI_FLASH_BOOT_BASE != FAQIUJI_FLASH_BASE) || \
    (FAQIUJI_FLASH_APP_A_BASE != FAQIUJI_FLASH_BOOT_END) || \
    (FAQIUJI_FLASH_APP_B_BASE != FAQIUJI_FLASH_APP_A_END) || \
    (FAQIUJI_FLASH_OTA_META_BASE != FAQIUJI_FLASH_APP_B_END) || \
    (FAQIUJI_FLASH_CONFIG_BASE != FAQIUJI_FLASH_OTA_META_END) || \
    (FAQIUJI_FLASH_CONFIG_END != FAQIUJI_FLASH_END)
#error "FAQIUJI Flash regions must be contiguous and cover the configured Flash"
#endif

#if ((FAQIUJI_FLASH_BOOT_BASE % FAQIUJI_FLASH_SECTOR_SIZE) != 0U) || \
    ((FAQIUJI_FLASH_BOOT_SIZE % FAQIUJI_FLASH_SECTOR_SIZE) != 0U) || \
    ((FAQIUJI_FLASH_APP_A_BASE % FAQIUJI_FLASH_SECTOR_SIZE) != 0U) || \
    ((FAQIUJI_FLASH_APP_A_SIZE % FAQIUJI_FLASH_SECTOR_SIZE) != 0U) || \
    ((FAQIUJI_FLASH_APP_B_BASE % FAQIUJI_FLASH_SECTOR_SIZE) != 0U) || \
    ((FAQIUJI_FLASH_APP_B_SIZE % FAQIUJI_FLASH_SECTOR_SIZE) != 0U) || \
    ((FAQIUJI_FLASH_OTA_META_BASE % FAQIUJI_FLASH_SECTOR_SIZE) != 0U) || \
    ((FAQIUJI_FLASH_OTA_META_SIZE % FAQIUJI_FLASH_SECTOR_SIZE) != 0U) || \
    ((FAQIUJI_FLASH_CONFIG_BASE % FAQIUJI_FLASH_SECTOR_SIZE) != 0U) || \
    ((FAQIUJI_FLASH_CONFIG_SIZE % FAQIUJI_FLASH_SECTOR_SIZE) != 0U)
#error "FAQIUJI Flash regions must be aligned to erase-sector boundaries"
#endif

#endif
